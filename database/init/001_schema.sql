create table if not exists public.pro_players (
  account_id bigint primary key,
  data jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.match_cache (
  steam_id bigint primary key,
  pros jsonb not null,
  cached_at timestamptz not null default now()
);

create index if not exists match_cache_cached_at_idx
  on public.match_cache (cached_at);

create table if not exists public.pro_item_timings (
  id bigint generated by default as identity primary key,
  hero_id integer not null,
  hero_name text not null,
  item_key text not null,
  item_name text not null,
  role text not null default 'hard_carry',
  scenario text not null default 'stomp',
  optimal_minute numeric(5,2) not null,
  min_minute numeric(5,2),
  max_minute numeric(5,2),
  patch text,
  source text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_pro_item_timings_lookup
  on public.pro_item_timings (hero_id, role, scenario);

create unique index if not exists idx_pro_item_timings_unique_current
  on public.pro_item_timings (hero_id, item_key, role, scenario, coalesce(patch, 'current'));

